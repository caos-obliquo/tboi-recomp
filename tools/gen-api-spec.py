#!/usr/bin/env python3
"""Generate the Lua binding surface from recovered binary data.

Input is the per-class method list recovered from isaac-ng.exe's binding
tables: NUL-separated name tables clustered around 0x76xxxx, bucketed between
class anchors. Every name came out of the shipped binary, so this file is a
read-only record of what that binary exposes to Lua.

Two artifacts come out of here:

  bindings/isaac-api-spec.json   canonical, human-readable, for tooling
  include/isaec/api/generated/isaac_api_spec.hpp   compiled into isaec_lua

The header form exists so the build never needs a JSON parser at runtime.
Signatures are not recovered yet, so argc and returns are 0 and documented is
false throughout; filling those in is a separate pass over the disassembly.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

SOURCE_JSON = "/tmp/opencode/isaac-binding-clean.json"
SPEC_JSON = os.path.join(ROOT, "bindings", "isaac-api-spec.json")
SPEC_HEADER = os.path.join(ROOT, "include", "isaec", "api", "generated", "isaac_api_spec.hpp")

# Inheritance recovered from the binary's metatable __parent links. Classes
# absent from this map are registered without a parent.
PARENTS = {
    "EntityPlayer": "Entity",
    "EntityPickup": "Entity",
    "EntityFamiliar": "Entity",
    "EntityProjectile": "Entity",
    "EntityBomb": "Entity",
    "EntityLaser": "Entity",
    "EntityKnife": "Entity",
    "EntityTear": "Entity",
}


def cxx_escape(name):
    out = []
    for ch in name:
        if ch.isalnum() or ch == "_":
            out.append(ch)
        else:
            out.append("\\x%02x" % ord(ch))
    return "".join(out)


def emit_json(source, classes):
    spec = {
        "source": source,
        "count": sum(len(c["methods"]) for c in classes),
        "classes": [
            {
                "name": c["name"],
                "parent": c["parent"],
                "methods": [{"name": m, "argc": 0, "returns": 0, "documented": False} for m in c["methods"]],
            }
            for c in classes
        ],
    }
    os.makedirs(os.path.dirname(SPEC_JSON), exist_ok=True)
    with open(SPEC_JSON, "w") as fh:
        json.dump(spec, fh, indent=1, sort_keys=True)
        fh.write("\n")


def emit_header(source, classes):
    lines = [
        "// Generated by tools/gen-api-spec.py. Do not edit.",
        "//",
        "// Source: " + source,
        "//",
        "// Every name below was recovered from isaac-ng.exe's binding tables. Signatures",
        "// are not recovered yet, so argc and returns are 0 and documented is false.",
        "",
        "#ifndef ISAEC_API_GENERATED_ISAAC_API_SPEC_HPP",
        "#define ISAEC_API_GENERATED_ISAAC_API_SPEC_HPP",
        "",
        "#include <cstddef>",
        "#include <vector>",
        "",
        '#include "isaec/api/registry.hpp"',
        "",
        "namespace isaec::api::generated {",
        "",
        "inline std::vector<ClassSpec> isaac_api_spec() {",
        "    return {",
    ]
    for cls in classes:
        lines.append("        ClassSpec{")
        lines.append('            "%s",' % cxx_escape(cls["name"]))
        lines.append('            "%s",' % cxx_escape(cls["parent"]))
        if cls["methods"]:
            lines.append("            {")
            for m in cls["methods"]:
                lines.append('                MethodSpec{"%s"},' % cxx_escape(m))
            lines.append("            },")
        else:
            lines.append("            {},")
        lines.append("        },")
    lines += [
        "    };",
        "}",
        "",
        "}  // namespace isaec::api::generated",
        "",
        "#endif  // ISAEC_API_GENERATED_ISAAC_API_SPEC_HPP",
        "",
    ]
    os.makedirs(os.path.dirname(SPEC_HEADER), exist_ok=True)
    with open(SPEC_HEADER, "w") as fh:
        fh.write("\n".join(lines))


def main():
    if not os.path.exists(SOURCE_JSON):
        sys.stderr.write("missing recovered binding data: %s\n" % SOURCE_JSON)
        return 1
    with open(SOURCE_JSON) as fh:
        raw = json.load(fh)

    classes = []
    for name in sorted(raw):
        methods = sorted(set(raw[name]["api"]))
        classes.append(
            {"name": name, "parent": PARENTS.get(name, ""), "methods": methods}
        )

    source = "isaac-ng.exe binding tables (0x76xxxx region)"
    emit_json(source, classes)
    emit_header(source, classes)

    total = sum(len(c["methods"]) for c in classes)
    print("generated %d classes / %d methods" % (len(classes), total))
    print("  " + SPEC_JSON)
    print("  " + SPEC_HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())