#!/usr/bin/env python3
"""Generate the plain-field class tables from the measured field layout.

Input is bindings/code-derived-field-layout.json: the field layout of the
game objects, recovered from isaac-ng.exe by tools/probe_field_layout.py
(see docs/binding-surface-findings.md §22). Every offset and every type in
that file was read out of the shipped binary: the offset is the property
upvalue (or the offset the property's accessor reads) and the type is the
push helper the property's getter calls.

Two artifacts come out of here:

  include/isaec/api/generated/field_classes.hpp   the per-class field tables
  src/api/field_classes_generated.cpp             the installer for them

Only the *plain* fields are emitted: int, float and bool. A field whose type
is `object` points into the game's own heap, and the game is not part of this
build, so those members stay the loud stubs of the generated API spec. A
field whose type could not be recovered is skipped for the same reason.

The layout JSON needs the binary and is refreshed by hand:

  python3 tools/probe_field_layout.py isaac-ng.exe \
      --cache disasm.txt --surface bindings/code-derived-surface.json \
      --json-out bindings/code-derived-field-layout.json

The C++ tables are generated from that JSON alone, so the CI check can
regenerate and diff them without the binary.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

LAYOUT_JSON = os.path.join(ROOT, "bindings", "code-derived-field-layout.json")
HEADER_OUT = os.path.join(ROOT, "include", "isaec", "api", "generated",
                          "field_classes.hpp")
SOURCE_OUT = os.path.join(ROOT, "src", "api", "field_classes_generated.cpp")

# The field types the port can hold in its own payload. "object" and
# "string" point into the game's heap, and "unknown" means the getter's
# push helper was not recognised.
PLAIN_TYPES = {
    "int": "FieldType::Int",
    "float": "FieldType::Float",
    "bool": "FieldType::Bool",
}


def camel(name: str) -> str:
    """The class name as a C++ identifier."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def collect(layout: dict) -> list[dict]:
    """The classes that have at least one plain field, with their fields."""
    out = []
    for class_name, entry in sorted(layout.get("classes", {}).items()):
        fields = [f for f in entry.get("fields", [])
                  if f.get("type") in PLAIN_TYPES and f.get("offset") is not None]
        if not fields:
            continue
        fields.sort(key=lambda f: f["offset"])
        out.append({
            "name": class_name,
            "size": int(entry.get("size") or 0),
            "fields": fields,
        })
    return out


def render_header(classes: list[dict], source: str) -> str:
    lines = [
        "// Generated by tools/gen-field-classes.py. Do not edit.",
        "//",
        f"// Source: {source}",
        "//",
        "// Every offset and every type below was recovered from isaac-ng.exe's",
        "// own property getters (see tools/probe_field_layout.py and",
        "// docs/binding-surface-findings.md §22). The payload of an instance is",
        "// the port's own bytes laid out like the game's object, so a field is",
        "// read and written at the game's offset.",
        "//",
        "// Only the plain fields are here: a field of type `object` points into",
        "// the game's heap, and the game is not part of this build, so those",
        "// members stay the loud stubs of the generated API spec.",
        "",
        "#ifndef ISAEC_API_GENERATED_FIELD_CLASSES_HPP",
        "#define ISAEC_API_GENERATED_FIELD_CLASSES_HPP",
        "",
        "#include <cstddef>",
        "",
        '#include "isaec/api/field_class.hpp"',
        "",
        "namespace isaec::api::generated {",
        "",
    ]
    for entry in classes:
        ident = camel(entry["name"])
        lines.append(f"// {entry['name']}: {len(entry['fields'])} plain fields.")
        lines.append(f"inline constexpr usize k{ident}Size = {entry['size']};")
        lines.append(f"inline constexpr FieldSpec k{ident}Fields[] = {{")
        for field in entry["fields"]:
            type_name = PLAIN_TYPES[field["type"]]
            lines.append(
                f'    {{"{field["name"]}", {int(field["offset"])}, {type_name}}},')
        lines.append("};")
        lines.append("")

    lines.append("// The installer walks this table.")
    lines.append("struct FieldClassTable {")
    lines.append("    const char* name;")
    lines.append("    usize object_size;")
    lines.append("    const FieldSpec* fields;")
    lines.append("    usize field_count;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr FieldClassTable kFieldClassTables[] = {")
    for entry in classes:
        ident = camel(entry["name"])
        lines.append(
            f'    {{"{entry["name"]}", k{ident}Size, k{ident}Fields, '
            f'{len(entry["fields"])}}},')
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace isaec::api::generated")
    lines.append("")
    lines.append("namespace isaec::api {")
    lines.append("")
    lines.append("// Installs every plain field class, replacing the stub the")
    lines.append("// generated API spec installed for the same members.")
    lines.append("void install_field_classes(Binding& binding);")
    lines.append("")
    lines.append("}  // namespace isaec::api")
    lines.append("")
    lines.append("#endif  // ISAEC_API_GENERATED_FIELD_CLASSES_HPP")
    lines.append("")
    return "\n".join(lines)


def render_source(classes: list[dict]) -> str:
    lines = [
        "// Generated by tools/gen-field-classes.py. Do not edit.",
        "",
        '#include "isaec/api/field_class.hpp"',
        '#include "isaec/api/generated/field_classes.hpp"',
        "",
        "namespace isaec::api {",
        "",
        "void install_field_classes(Binding& binding) {",
        "#if ISAEC_HAS_LUA",
        "    for (const auto& table : generated::kFieldClassTables) {",
        "        FieldClass::install(binding, table.name, table.object_size,",
        "                           table.fields, table.field_count);",
        "    }",
        "#else",
        "    (void)binding;",
        "#endif",
        "}",
        "",
        "}  // namespace isaec::api",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        print("SELF-TEST PASSED")
        return 0

    with open(LAYOUT_JSON, encoding="utf-8") as handle:
        layout = json.load(handle)

    classes = collect(layout)
    if not classes:
        print("no plain field class found in", LAYOUT_JSON, file=sys.stderr)
        return 1

    header = render_header(classes, os.path.relpath(LAYOUT_JSON, ROOT))
    source = render_source(classes)

    os.makedirs(os.path.dirname(HEADER_OUT), exist_ok=True)
    os.makedirs(os.path.dirname(SOURCE_OUT), exist_ok=True)
    for path, text in ((HEADER_OUT, header), (SOURCE_OUT, source)):
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)

    fields = sum(len(entry["fields"]) for entry in classes)
    print(f"generated {len(classes)} field classes / {fields} plain fields")
    print(f"  {os.path.relpath(HEADER_OUT, ROOT)}")
    print(f"  {os.path.relpath(SOURCE_OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
