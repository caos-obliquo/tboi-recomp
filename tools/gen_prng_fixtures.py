#!/usr/bin/env python3
"""Regenerate tests/prng_fixtures.inc with the corrected PRNG seed prep.

Companion to docs/arch000-format.md section 9.2 (corrected 2026-11-17). The
previous fixtures pinned the C++ decoder to the Python reference while both
shared one wrong transcription of the seed prep. This generator is
self-contained: it does NOT read or import tools/isaac-archive.py (user-owned,
untouched) and implements the disassembled formula on its own:

    h = (((seed << 15) ^ seed) << 8) ^ (seed >> 9) ^ seed

Input bytes are a deterministic per-case stream so re-running produces
identical fixtures. Run: python3 tools/gen_prng_fixtures.py
Writes: tests/prng_fixtures.inc (overwrites).
"""

import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "prng_fixtures.inc"

CASES = [  # name, seed, length
    ("seed0", 0, 64),
    ("seed1", 1, 257),
    ("asset", 4182917767, 1024),
    ("big", 3735928559, 3000),
    ("oddlen", 16909060, 4093),
]

U32 = 0xFFFFFFFF
MULT = 0x4C957F2D5851F42D
INC = 0x7F
MASK64 = 0xFFFFFFFFFFFFFFFF


class PrngStream:
    def __init__(self, seed):
        h = (((seed << 15) ^ seed) << 8) ^ (seed >> 9) ^ seed
        h &= U32
        self.state = (((seed & U32) << 32) | h) & MASK64

    def next_word(self):
        self.state = (self.state * MULT + INC) & MASK64
        hi = (self.state >> 32) & U32
        v = (((self.state >> 27) & U32) ^ (hi >> 13)) & U32
        n = hi >> 27
        # n == 0 would ask for a rotate by 0/32; C++ reference masks as well:
        return ((v >> n) | (v << ((32 - n) & 31))) & U32


def decode(buf: bytes, seed: int) -> bytes:
    prng = PrngStream(seed & U32)
    out = bytearray(buf)
    for i in range(0, len(out), 4):
        word = prng.next_word()
        for b in range(4):
            if i + b < len(out):
                out[i + b] ^= (word >> (8 * b)) & 0xFF
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    vals = ",".join(str(b) for b in data)
    return f"static const u8 {name}[] = {{{vals}}};\n"


def main() -> None:
    rng_cases = []
    for name, seed, length in CASES:
        raw = random.Random("isaec-prng-" + name).randbytes(length)
        exp = decode(raw, seed)
        rng_cases.append((name, seed, raw, exp))

    chunks = [
        "// Generated by tools/gen_prng_fixtures.py (2026-11-17).\n",
        "// Regenerate with: python3 tools/gen_prng_fixtures.py\n",
        "// Seed prep matches the disassembled generator at VA 0xaa93e0\n",
        "// (docs/arch000-format.md section 9.2, corrected 2026-11-17).\n",
        "\n",
        "struct PrngFixture { const char* name; const u32 seed; const u8* input; usize input_size; const u8* expected; usize expected_size; };\n",
        "\n",
    ]
    for name, _seed, raw, exp in rng_cases:
        chunks.append(c_array(f"kPrngIn_{name}", raw))
        chunks.append(c_array(f"kPrngExp_{name}", exp))
        chunks.append("\n")

    chunks.append("static const PrngFixture kPrngFixtures[] = {\n")
    for name, seed, raw, _exp in rng_cases:
        chunks.append(
            f'    {{"{name}", {seed}u, kPrngIn_{name}, {len(raw)},'
            f' kPrngExp_{name}, {len(raw)}}},\n'
        )
    chunks.append("};\n")
    chunks.append(f"static const usize kPrngFixtureCount = {len(rng_cases)};\n")

    OUT.write_text("".join(chunks))
    print(f"wrote {OUT} ({len(rng_cases)} cases)")


if __name__ == "__main__":
    main()
